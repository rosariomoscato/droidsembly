// npm does not implement GitHub's #gh-*-mode-only image selectors.
// Keep one self-contained image with its own opaque panel for either page theme.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const source = fs.readFileSync(path.join(root, 'client/public/icons/logo-light.svg'), 'utf8').replaceAll('\r\n', '\n');
const output = path.join(root, 'docs/branding/logo-readme.svg');
assert.ok(source.startsWith('<svg '));
assert.equal(source.split('</defs>').length, 2);
const generated = source.replace('</defs>', '</defs>\n<!-- Generated by scripts/build-readme-logo.mjs; opaque panel preserves contrast on light and dark hosts. -->\n<rect width="560" height="164" rx="12" fill="#ffffff"/>');

if (process.argv.includes('--check')) {
  assert.equal(fs.readFileSync(output, 'utf8').replaceAll('\r\n', '\n'), generated, 'Regenerate the README logo after changing logo-light.svg');
  for (const name of ['README.md', 'README.it.md']) {
    const readme = fs.readFileSync(path.join(root, name), 'utf8');
    const header = readme.slice(0, readme.indexOf('</p>') + 4);
    assert.equal((header.match(/<img\b/g) ?? []).length, 1, `${name}: exactly one header logo`);
    assert.ok(header.includes('https://raw.githubusercontent.com/rosariomoscato/droidsembly/main/docs/branding/logo-readme.svg'));
    assert.ok(header.includes('width="360"'));
    assert.ok(header.includes('alt="Droidsembly — Software, assembled by agents."'));
    assert.ok(!readme.includes('#gh-'), `${name}: no GitHub-only theme selectors`);
  }
  assert.ok(!/<(?:image|script|foreignObject)\b|(?:href|xlink:href)=["'](?!#)|@import|prefers-color-scheme/i.test(generated), 'The image must not depend on external resources or host theme support');
  for (const match of generated.matchAll(/url\(([^)]+)\)/g)) {
    assert.ok(/^(?:#|data:font\/ttf;base64,)/.test(match[1]), 'Only local gradients and the embedded font are allowed');
  }
  console.log('README logo: generated asset, single EN/IT header image and theme-independent rendering checks passed');
} else {
  fs.writeFileSync(output, generated);
  console.log('Generated docs/branding/logo-readme.svg');
}
